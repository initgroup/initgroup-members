-- [ANNUAL_EXPENSE_GET]
SELECT AMOUNT
     , NOTE
  FROM "INIT$_TB_YEAR_EXPENSE"
 WHERE 1=1
   AND PLAN_YEAR = :year
;
-- [ANNUAL_EXPENSE_SAVE]
MERGE /*+ DISABLE_PARALLEL_DML NO_PARALLEL */ INTO "INIT$_TB_YEAR_EXPENSE" E
USING (SELECT :year AS PLAN_YEAR FROM DUAL) S
   ON (E.PLAN_YEAR = S.PLAN_YEAR)
WHEN MATCHED THEN UPDATE SET
    E.AMOUNT = :amount
  , E.NOTE = :note
WHEN NOT MATCHED THEN INSERT (
    PLAN_YEAR
  , AMOUNT
  , NOTE
)
VALUES (
    :year
  , :amount
  , :note
)
;
-- [ANNUAL_V4_MIGRATE_EXPENSES]
INSERT /*+ DISABLE_PARALLEL_DML NO_PARALLEL */ INTO "INIT$_TB_YEAR_EXPENSE" (
    PLAN_YEAR
  , AMOUNT
  , NOTE
)
SELECT E.PLAN_YEAR
     , SUM(E.AMOUNT)
     , 'Annual total migrated from monthly company costs; source details retained'
  FROM "INIT$_TB_COMPANY_EXPENSE" E
  JOIN "INIT$_TB_TARGET_YEAR" Y ON Y.PLAN_YEAR = E.PLAN_YEAR
 WHERE 1=1
   AND Y.MODEL_VERSION < 4
   AND NOT EXISTS (SELECT 1 FROM "INIT$_TB_YEAR_EXPENSE" A WHERE A.PLAN_YEAR = E.PLAN_YEAR)
 GROUP BY E.PLAN_YEAR
;
-- [ANNUAL_V4_MARK_MIGRATED]
UPDATE /*+ DISABLE_PARALLEL_DML NO_PARALLEL */ "INIT$_TB_TARGET_YEAR"
   SET MODEL_VERSION = 4
 WHERE 1=1
   AND MODEL_VERSION < 4
;
-- [ANNUAL_YEAR_CLOSE]
UPDATE /*+ DISABLE_PARALLEL_DML NO_PARALLEL */ "INIT$_TB_TARGET_YEAR"
   SET YEAR_SNAPSHOT = :snapshot
     , YEAR_CLOSED_AT = SYSTIMESTAMP
     , YEAR_CLOSED_BY = :actor
 WHERE 1=1
   AND PLAN_YEAR = :year
   AND YEAR_CLOSED_AT IS NULL
;
