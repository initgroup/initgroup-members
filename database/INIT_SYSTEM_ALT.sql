            DBMS_OUTPUT.PUT_LINE(
                '[WARN] UNIQUE INDEX ' || P_INDEX_NAME
             || ' skipped because ' || V_DUPLICATE_GROUP_COUNT
             || ' duplicate group(s) exist; resolve duplicates and rerun INIT_SYSTEM_ALT.sql'
            );
        ELSE
            RUN_DDL(P_DDL, 'CREATE UNIQUE INDEX ' || P_INDEX_NAME);
        END IF;
    END;

