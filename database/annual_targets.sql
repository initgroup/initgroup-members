-- [ANNUAL_HISTORY_GET]
SELECT USER_ID
     , EFFECTIVE_FROM
     , USER_NAME
     , DEPARTMENT_CODE
     , DEPARTMENT_NAME
     , EMPLOYMENT_TYPE_CODE
     , EMPLOYMENT_STATUS_CODE
     , HIRE_DATE
     , RETIREMENT_DATE
     , SOURCE_CODE
  FROM "INIT$_TB_STAFF_HISTORY"
 ORDER BY USER_ID, EFFECTIVE_FROM
;
-- [ANNUAL_HISTORY_USER_GET]
SELECT USER_ID
     , EFFECTIVE_FROM
     , USER_NAME
     , DEPARTMENT_CODE
     , DEPARTMENT_NAME
     , EMPLOYMENT_TYPE_CODE
     , EMPLOYMENT_STATUS_CODE
     , HIRE_DATE
     , RETIREMENT_DATE
     , SOURCE_CODE
     , TO_CHAR(RECORDED_AT, 'YYYY-MM-DD"T"HH24:MI:SS.FF6') AS VERSION_TOKEN
  FROM "INIT$_TB_STAFF_HISTORY"
 WHERE USER_ID = :userId
 ORDER BY EFFECTIVE_FROM
;
-- [ANNUAL_HISTORY_UPSERT]
MERGE /*+ DISABLE_PARALLEL_DML NO_PARALLEL */ INTO "INIT$_TB_STAFF_HISTORY" H
USING (SELECT :userId AS USER_ID, :effectiveFrom AS EFFECTIVE_FROM FROM DUAL) S
   ON (H.USER_ID = S.USER_ID AND H.EFFECTIVE_FROM = S.EFFECTIVE_FROM)
WHEN MATCHED THEN UPDATE SET
    H.USER_NAME = :name
  , H.DEPARTMENT_CODE = :department
  , H.DEPARTMENT_NAME = :departmentName
  , H.EMPLOYMENT_TYPE_CODE = :employmentType
  , H.EMPLOYMENT_STATUS_CODE = :employmentStatus
  , H.HIRE_DATE = :hireDate
  , H.RETIREMENT_DATE = :retirementDate
  , H.SOURCE_CODE = 'VERIFIED'
  , H.RECORDED_AT = SYSTIMESTAMP
WHEN NOT MATCHED THEN INSERT (
    USER_ID, EFFECTIVE_FROM, USER_NAME, DEPARTMENT_CODE, DEPARTMENT_NAME
  , EMPLOYMENT_TYPE_CODE
  , EMPLOYMENT_STATUS_CODE
  , HIRE_DATE
  , RETIREMENT_DATE
  , SOURCE_CODE
)
VALUES (
    :userId
  , :effectiveFrom
  , :name
  , :department
  , :departmentName
  , :employmentType
  , :employmentStatus
  , :hireDate
  , :retirementDate
  , 'VERIFIED'
)
;
