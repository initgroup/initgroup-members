-- [ANNUAL_PROJECTS]
SELECT PROJECT_ID
     , PROJECT_NAME
     , STATUS_CODE
     , CONTRACT_AMOUNT_VAT
     , ORDER_AMOUNT_VAT
     , PARTICIPATION_RATE
     , DEPARTMENT_CODE
     , BID_DATE
     , PROJECT_START_DATE
     , PROJECT_END_DATE
  FROM "INIT$_TB_PROJECT"
 WHERE (PROJECT_START_DATE <= TO_DATE(TO_CHAR(:year) || '1231', 'YYYYMMDD')
   AND PROJECT_END_DATE >= TO_DATE(TO_CHAR(:year) || '0101', 'YYYYMMDD'))
    OR EXISTS (SELECT 1 FROM "INIT$_TB_PROJECT_REV_YEAR" R WHERE R.PROJECT_ID = "INIT$_TB_PROJECT".PROJECT_ID AND R.REVENUE_YEAR = :year)
 ORDER BY PROJECT_START_DATE, PROJECT_ID
;
-- [ANNUAL_CLOSE_GET]
SELECT MONTH_KEY
     , SNAPSHOT_JSON
     , CLOSED_AT
  FROM "INIT$_TB_MONTH_CLOSE"
 WHERE SUBSTR(MONTH_KEY, 1, 4) = TO_CHAR(:year)
 ORDER BY MONTH_KEY
;
-- [ANNUAL_LAST_CLOSE]
SELECT MAX(CLOSED_MONTH)
  FROM (
       SELECT MONTH_KEY AS CLOSED_MONTH FROM "INIT$_TB_MONTH_CLOSE"
       UNION ALL
       SELECT TO_CHAR(PLAN_YEAR) || '-12' FROM "INIT$_TB_TARGET_YEAR" WHERE YEAR_CLOSED_AT IS NOT NULL
       )
;
