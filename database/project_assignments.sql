-- [PROJECT_ASSIGNMENT_WORKSPACE_ASSIGNMENTS]
SELECT A.ASSIGNMENT_ID
     , A.PROJECT_ID
     , A.USER_ID
     , A.COMPANY_EMPLOYEE_ID
     , A.PROJECT_COMPANY_ID
     , CASE WHEN A.USER_ID IS NOT NULL THEN 'USER' ELSE 'COMPANY_EMPLOYEE' END AS WORKER_TYPE_CODE
     , NVL(U.USER_NAME, E.EMPLOYEE_NAME) AS EMPLOYEE_NAME
     , CASE
           WHEN A.USER_ID IS NOT NULL THEN '인아이티'
           ELSE NVL(EC.COMPANY_NAME, PC.COMPANY_NAME)
       END AS COMPANY_NAME
     , CASE
           WHEN A.USER_ID IS NOT NULL THEN U.DEPARTMENT_NAME
           ELSE E.DEPARTMENT_NAME
       END AS DEPARTMENT_NAME
     , U.DEPARTMENT_CODE
     , A.ASSIGNMENT_START_DATE
     , A.ASSIGNMENT_END_DATE
     , A.ASSIGNMENT_STATUS_CODE
     , A.ALLOCATION_TYPE_CODE
     , A.DEFAULT_MM
     , A.WEEKLY_DAY_CODES
     , A.TOTAL_MM
     , A.COST_UNIT_PRICE
     , A.SALES_UNIT_PRICE
     , A.OPERATING_PROFIT
     , A.NOTE
     , A.PROJECT_ROLE_NAME
     , A.PRIMARY_DUTY
     , A.DISPLAY_ORDER
     , A.MONTHLY_ALLOCATION_JSON
     , TO_CHAR(NVL(A.UPDATED_AT, A.CREATED_AT), 'YYYY-MM-DD"T"HH24:MI:SS.FF6') AS VERSION_TOKEN
  FROM "INIT$_TB_PROJECT_ASSIGNMENT" A
  JOIN "INIT$_TB_PROJECT" P
    ON P.PROJECT_ID = A.PROJECT_ID
  LEFT JOIN "INIT$_TB_USER" U
    ON U.USER_ID = A.USER_ID
  LEFT JOIN "INIT$_TB_COMPANY_EMPLOYEE" E
    ON E.COMPANY_EMPLOYEE_ID = A.COMPANY_EMPLOYEE_ID
  LEFT JOIN "INIT$_TB_PROJECT_COMPANY" PC
    ON PC.PROJECT_COMPANY_ID = A.PROJECT_COMPANY_ID
  LEFT JOIN "INIT$_TB_COMPANY" EC
    ON EC.COMPANY_ID = E.COMPANY_ID
 WHERE 1=1
   AND P.PROJECT_START_DATE <= TO_DATE(TO_CHAR(:projectYear) || '1231', 'YYYYMMDD')
   AND P.PROJECT_END_DATE >= TO_DATE(TO_CHAR(:projectYear) || '0101', 'YYYYMMDD')
   AND P.STATUS_CODE <> 'CANCELLED'
 ORDER BY A.PROJECT_ID
        , A.DISPLAY_ORDER
        , A.ASSIGNMENT_START_DATE
        , EMPLOYEE_NAME
;

