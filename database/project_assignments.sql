-- [PROJECT_ASSIGNMENT_SUMMARY]
SELECT P.CONTRACT_AMOUNT_VAT
     , NVL(C.COMPANY_SHARE_RATE, 0) AS COMPANY_SHARE_RATE
     , NVL(C.COMPANY_ALLOCATED_AMOUNT, 0) AS COMPANY_ALLOCATED_AMOUNT
     , NVL(A.TOTAL_MM, 0) AS TOTAL_MM
     , NVL(A.TOTAL_COST_AMOUNT, 0) AS TOTAL_COST_AMOUNT
     , NVL(A.TOTAL_SALES_AMOUNT, 0) AS TOTAL_SALES_AMOUNT
     , NVL(A.OPERATING_PROFIT, 0) AS OPERATING_PROFIT
  FROM "INIT$_TB_PROJECT" P
  LEFT JOIN (
        SELECT PROJECT_ID
             , SUM(SHARE_RATE) AS COMPANY_SHARE_RATE
             , SUM(ALLOCATED_AMOUNT) AS COMPANY_ALLOCATED_AMOUNT
          FROM (
                SELECT C.PROJECT_ID
                     , C.SHARE_RATE
                     , ROUND(P2.CONTRACT_AMOUNT_VAT * C.SHARE_RATE / 100) AS ALLOCATED_AMOUNT
                  FROM "INIT$_TB_PROJECT_COMPANY" C
                  JOIN "INIT$_TB_PROJECT" P2
                    ON P2.PROJECT_ID = C.PROJECT_ID
               )
         GROUP BY PROJECT_ID
       ) C
    ON C.PROJECT_ID = P.PROJECT_ID
  LEFT JOIN (
        SELECT PROJECT_ID
             , SUM(TOTAL_MM) AS TOTAL_MM
             , SUM(TOTAL_COST_AMOUNT) AS TOTAL_COST_AMOUNT
             , SUM(TOTAL_SALES_AMOUNT) AS TOTAL_SALES_AMOUNT
             , SUM(OPERATING_PROFIT) AS OPERATING_PROFIT
          FROM "INIT$_TB_PROJECT_ASSIGNMENT"
         GROUP BY PROJECT_ID
       ) A
    ON A.PROJECT_ID = P.PROJECT_ID
 WHERE P.PROJECT_ID = :projectId
;

