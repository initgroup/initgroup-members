-- [PLANNING_REFERENCE_PROJECTS]
SELECT P.PROJECT_ID
     , P.PROJECT_YEAR
     , P.PROJECT_NAME
     , P.CUSTOMER_NAME
     , TO_CHAR(P.PROJECT_START_DATE, 'YYYY-MM-DD') AS PROJECT_START_DATE
     , TO_CHAR(P.PROJECT_END_DATE, 'YYYY-MM-DD') AS PROJECT_END_DATE
     , P.ORDER_AMOUNT_VAT
     , P.CONTRACT_AMOUNT_VAT
     , P.STATUS_CODE
 FROM INIT$_TB_PROJECT P
 WHERE 1=1
   AND P.STATUS_CODE <> 'CANCELLED'
   AND P.PROJECT_START_DATE <= TO_DATE(TO_CHAR(:planYear) || '1231', 'YYYYMMDD')
   AND P.PROJECT_END_DATE >= TO_DATE(TO_CHAR(:planYear) || '0101', 'YYYYMMDD')
 ORDER BY P.PROJECT_START_DATE
        , P.PROJECT_END_DATE
        , P.PROJECT_NAME
;

-- [PLANNING_REFERENCE_USERS]
SELECT U.USER_ID
     , U.EMPLOYEE_NO
     , U.USER_NAME AS EMPLOYEE_NAME
     , U.DEPARTMENT_NAME
     , U.POSITION_NAME
     , U.JOB_TITLE
     , U.EMAIL
     , U.GENDER_CODE
     , TO_CHAR(U.BIRTH_DATE, 'YYYY-MM-DD') AS BIRTH_DATE
     , U.TECHNICAL_GRADE_CODE
     , U.CAREER_MONTHS
     , U.WORK_LOCATION
     , U.MOBILE_PHONE
     , U.OFFICE_PHONE
     , U.PHOTO_FILE_NAME
     , U.PHOTO_UPDATED_AT
     , U.EMPLOYMENT_TYPE_CODE
     , 'INTERNAL' AS WORKER_TYPE_CODE
     , '인아이티' AS COMPANY_NAME
     , TO_CHAR(U.HIRE_DATE, 'YYYY-MM-DD') AS AVAILABLE_START_DATE
     , TO_CHAR(U.RETIREMENT_DATE, 'YYYY-MM-DD') AS AVAILABLE_END_DATE
 FROM INIT$_TB_USER U
 WHERE 1=1
   AND U.USE_YN = 'Y'
   AND U.EMPLOYMENT_STATUS_CODE <> 'RETIRED'
   AND (U.HIRE_DATE IS NULL OR U.HIRE_DATE <= TO_DATE(TO_CHAR(:planYear) || '1231', 'YYYYMMDD'))
   AND (U.RETIREMENT_DATE IS NULL OR U.RETIREMENT_DATE >= TO_DATE(TO_CHAR(:planYear) || '0101', 'YYYYMMDD'))
 ORDER BY U.DEPARTMENT_NAME NULLS LAST
        , U.USER_NAME
;

-- [PLANNING_REFERENCE_COMPANY_EMPLOYEES]
SELECT E.COMPANY_EMPLOYEE_ID
     , E.EMPLOYEE_NO
     , E.EMPLOYEE_NAME
     , E.DEPARTMENT_NAME
     , E.POSITION_NAME
     , E.JOB_TITLE
     , E.EMAIL
     , E.MOBILE_PHONE
     , E.GENDER_CODE
     , E.AGE_YEARS
     , E.TECHNICAL_GRADE_CODE
     , E.CAREER_MONTHS
     , C.COMPANY_TYPE_CODE AS WORKER_TYPE_CODE
     , C.COMPANY_NAME
     , TO_CHAR(E.JOIN_DATE, 'YYYY-MM-DD') AS AVAILABLE_START_DATE
     , TO_CHAR(E.LEAVE_DATE, 'YYYY-MM-DD') AS AVAILABLE_END_DATE
  FROM INIT$_TB_COMPANY_EMPLOYEE E
  JOIN INIT$_TB_COMPANY C
    ON C.COMPANY_ID = E.COMPANY_ID
 WHERE 1=1
   AND E.USE_YN = 'Y'
   AND C.USE_YN = 'Y'
   AND C.COMPANY_TYPE_CODE = 'PARTNER'
   AND (E.JOIN_DATE IS NULL OR E.JOIN_DATE <= TO_DATE(TO_CHAR(:planYear) || '1231', 'YYYYMMDD'))
   AND (E.LEAVE_DATE IS NULL OR E.LEAVE_DATE >= TO_DATE(TO_CHAR(:planYear) || '0101', 'YYYYMMDD'))
 ORDER BY C.COMPANY_TYPE_CODE
        , C.COMPANY_NAME
        , E.EMPLOYEE_NAME
;

-- [PLANNING_REFERENCE_ACTUAL_ASSIGNMENTS]
SELECT A.ASSIGNMENT_ID
     , A.USER_ID
     , A.COMPANY_EMPLOYEE_ID
     , NVL(U.USER_NAME, E.EMPLOYEE_NAME) AS EMPLOYEE_NAME
     , A.MONTHLY_ALLOCATION_JSON
  FROM INIT$_TB_PROJECT_ASSIGNMENT A
  JOIN INIT$_TB_PROJECT P
    ON P.PROJECT_ID = A.PROJECT_ID
  LEFT JOIN INIT$_TB_USER U
    ON U.USER_ID = A.USER_ID
  LEFT JOIN INIT$_TB_COMPANY_EMPLOYEE E
    ON E.COMPANY_EMPLOYEE_ID = A.COMPANY_EMPLOYEE_ID
 WHERE 1=1
   AND P.STATUS_CODE <> 'CANCELLED'
   AND A.ASSIGNMENT_END_DATE >= TO_DATE(TO_CHAR(:planYear) || '0101', 'YYYYMMDD')
   AND A.ASSIGNMENT_START_DATE <= TO_DATE(TO_CHAR(:planYear) || '1231', 'YYYYMMDD')
;

-- [PLANNING_SCENARIO_LIST]
SELECT S.SCENARIO_ID
     , S.PLAN_YEAR
     , S.SCENARIO_NAME
     , S.STATUS_CODE
     , S.REVISION_NO
     , S.DESCRIPTION
     , S.CONFIRMED_AT
     , S.CREATED_AT
     , S.UPDATED_AT
     , (SELECT COUNT(*)
          FROM INIT$_TB_PLAN_PROJECT SP
         WHERE SP.SCENARIO_ID = S.SCENARIO_ID) AS PROJECT_COUNT
     , (SELECT COUNT(*)
          FROM INIT$_TB_PLAN_PROJECT SP
          JOIN INIT$_TB_PLAN_ASSIGNMENT SA
            ON SA.SCENARIO_PROJECT_ID = SP.SCENARIO_PROJECT_ID
         WHERE SP.SCENARIO_ID = S.SCENARIO_ID) AS ASSIGNMENT_COUNT
     , (SELECT NVL(SUM(SA.TOTAL_SALES_AMOUNT), 0)
          FROM INIT$_TB_PLAN_PROJECT SP
          JOIN INIT$_TB_PLAN_ASSIGNMENT SA
            ON SA.SCENARIO_PROJECT_ID = SP.SCENARIO_PROJECT_ID
         WHERE SP.SCENARIO_ID = S.SCENARIO_ID) AS TOTAL_SALES_AMOUNT
     , (SELECT NVL(SUM(SA.TOTAL_COST_AMOUNT), 0)
          FROM INIT$_TB_PLAN_PROJECT SP
          JOIN INIT$_TB_PLAN_ASSIGNMENT SA
            ON SA.SCENARIO_PROJECT_ID = SP.SCENARIO_PROJECT_ID
         WHERE SP.SCENARIO_ID = S.SCENARIO_ID) AS TOTAL_COST_AMOUNT
  FROM INIT$_TB_PLAN_SCENARIO S
 WHERE 1=1
   AND S.PLAN_YEAR = :planYear
 ORDER BY CASE S.STATUS_CODE WHEN 'DRAFT' THEN 1 WHEN 'CONFIRMED' THEN 2 ELSE 3 END
        , NVL(S.UPDATED_AT, S.CREATED_AT) DESC
        , S.SCENARIO_ID DESC
;

