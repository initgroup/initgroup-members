-- [PLANNING_SCENARIO_ASSIGNMENT_LIST]
SELECT SA.PLAN_ASSIGNMENT_ID
     , SA.SCENARIO_PROJECT_ID
     , SA.USER_ID
     , SA.COMPANY_EMPLOYEE_ID
     , CASE
           WHEN SA.USER_ID IS NOT NULL THEN U.USER_NAME
           ELSE E.EMPLOYEE_NAME
       END AS EMPLOYEE_NAME
     , CASE
           WHEN SA.USER_ID IS NOT NULL THEN U.DEPARTMENT_NAME
           ELSE E.DEPARTMENT_NAME
       END AS DEPARTMENT_NAME
     , CASE
           WHEN SA.USER_ID IS NOT NULL THEN U.POSITION_NAME
           ELSE E.POSITION_NAME
       END AS POSITION_NAME
     , CASE
           WHEN SA.USER_ID IS NOT NULL THEN 'INTERNAL'
           ELSE C.COMPANY_TYPE_CODE
       END AS WORKER_TYPE_CODE
     , CASE
           WHEN SA.USER_ID IS NOT NULL THEN '인아이티'
           ELSE C.COMPANY_NAME
       END AS COMPANY_NAME
     , TO_CHAR(SA.ASSIGNMENT_START_DATE, 'YYYY-MM-DD') AS ASSIGNMENT_START_DATE
     , TO_CHAR(SA.ASSIGNMENT_END_DATE, 'YYYY-MM-DD') AS ASSIGNMENT_END_DATE
     , SA.TOTAL_MM
     , SA.COST_UNIT_PRICE
     , SA.SALES_UNIT_PRICE
     , SA.TOTAL_COST_AMOUNT
     , SA.TOTAL_SALES_AMOUNT
     , SA.OPERATING_PROFIT
     , SA.SORT_ORDER
     , SA.NOTE
     , SA.PROJECT_ROLE_NAME
     , SA.PRIMARY_DUTY
  FROM INIT$_TB_PLAN_ASSIGNMENT SA
  LEFT JOIN INIT$_TB_USER U
    ON U.USER_ID = SA.USER_ID
  LEFT JOIN INIT$_TB_COMPANY_EMPLOYEE E
    ON E.COMPANY_EMPLOYEE_ID = SA.COMPANY_EMPLOYEE_ID
  LEFT JOIN INIT$_TB_COMPANY C
    ON C.COMPANY_ID = E.COMPANY_ID
 WHERE 1=1
   AND SA.SCENARIO_PROJECT_ID IN (
       SELECT SP.SCENARIO_PROJECT_ID
         FROM INIT$_TB_PLAN_PROJECT SP
        WHERE SP.SCENARIO_ID = :scenarioId
   )
 ORDER BY SA.SCENARIO_PROJECT_ID
        , SA.SORT_ORDER
        , SA.PLAN_ASSIGNMENT_ID
;

