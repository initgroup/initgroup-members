-- [ANNUAL_HISTORICAL_GET]
SELECT PLAN_YEAR
     , REVISION_NO
     , TARGET_AMOUNT
     , SALES_AMOUNT
     , NET_PROFIT
     , NOTE
     , ACTIVE_YN
  FROM "INIT$_TB_YEAR_HISTORY_TOTAL"
 WHERE 1=1
   AND PLAN_YEAR = :year
;
-- [ANNUAL_HISTORICAL_SAVE]
MERGE INTO "INIT$_TB_YEAR_HISTORY_TOTAL" H
USING (SELECT :year AS PLAN_YEAR FROM DUAL) S ON (H.PLAN_YEAR = S.PLAN_YEAR)
WHEN MATCHED THEN UPDATE SET
    H.REVISION_NO = H.REVISION_NO + 1
  , H.TARGET_AMOUNT = :targetAmount
  , H.SALES_AMOUNT = :salesAmount
  , H.NET_PROFIT = :netProfit
  , H.NOTE = :note
  , H.ACTIVE_YN = 'Y'
  , H.UPDATED_BY = :actor
  , H.UPDATED_AT = SYSTIMESTAMP
WHEN NOT MATCHED THEN INSERT (
    PLAN_YEAR
  , REVISION_NO
  , TARGET_AMOUNT
  , SALES_AMOUNT
  , NET_PROFIT
  , NOTE
  , ACTIVE_YN
  , UPDATED_BY
) VALUES (
    :year
  , 1
  , :targetAmount
  , :salesAmount
  , :netProfit
  , :note
  , 'Y'
  , :actor
)
;
-- [ANNUAL_HISTORICAL_DISABLE]
UPDATE "INIT$_TB_YEAR_HISTORY_TOTAL"
   SET ACTIVE_YN = 'N'
     , REVISION_NO = REVISION_NO + 1
     , UPDATED_BY = :actor
     , UPDATED_AT = SYSTIMESTAMP
 WHERE 1=1
   AND PLAN_YEAR = :year
;
-- [HISTORICAL_TOTALS_SCHEMA_STATUS]
SELECT COUNT(*) FROM USER_TABLES WHERE TABLE_NAME = 'INIT$_TB_YEAR_HISTORY_TOTAL'
;
-- [ANNUAL_HISTORICAL_TOUCH]
UPDATE "INIT$_TB_YEAR_HISTORY_TOTAL"
   SET REVISION_NO = REVISION_NO + 1
 WHERE PLAN_YEAR = :year
;
