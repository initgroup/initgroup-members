-- [ANNUAL_REVISIONS_GET]
SELECT SECTION_CODE
     , REVISION_NO
  FROM "INIT$_TB_TARGET_REVISION"
 WHERE 1=1
   AND PLAN_YEAR = :year
;
-- [ANNUAL_SECTION_UPDATE]
MERGE /*+ DISABLE_PARALLEL_DML NO_PARALLEL */ INTO "INIT$_TB_TARGET_REVISION" R
USING (SELECT :year AS PLAN_YEAR, :section AS SECTION_CODE FROM DUAL) S
   ON (R.PLAN_YEAR = S.PLAN_YEAR AND R.SECTION_CODE = S.SECTION_CODE)
WHEN MATCHED THEN UPDATE SET R.REVISION_NO = R.REVISION_NO + 1
WHEN NOT MATCHED THEN INSERT (
    PLAN_YEAR
  , SECTION_CODE
  , REVISION_NO
)
VALUES (
    S.PLAN_YEAR
  , S.SECTION_CODE
  , 1
)
;
-- [ANNUAL_V3_MIGRATE_STAFF]
INSERT /*+ DISABLE_PARALLEL_DML NO_PARALLEL */ INTO "INIT$_TB_YEAR_TARGET" (
    PLAN_YEAR
  , SCOPE_CODE
  , TARGET_KEY
  , USER_ID
  , USER_NAME
  , DEPARTMENT_CODE
  , DEPARTMENT_NAME
  , EMPLOYMENT_TYPE_CODE
  , TARGET_AMOUNT
)
SELECT T.PLAN_YEAR
     , 'STAFF'
     , TO_CHAR(T.USER_ID)
     , T.USER_ID
     , MAX(T.USER_NAME) KEEP (DENSE_RANK LAST ORDER BY T.MONTH_KEY, T.DEPARTMENT_CODE)
     , MAX(T.DEPARTMENT_CODE) KEEP (DENSE_RANK LAST ORDER BY T.MONTH_KEY, T.DEPARTMENT_CODE)
     , MAX(T.DEPARTMENT_NAME) KEEP (DENSE_RANK LAST ORDER BY T.MONTH_KEY, T.DEPARTMENT_CODE)
     , MAX(T.EMPLOYMENT_TYPE_CODE) KEEP (DENSE_RANK LAST ORDER BY T.MONTH_KEY, T.DEPARTMENT_CODE)
     , SUM(T.TARGET_AMOUNT)
  FROM "INIT$_TB_PERSON_TARGET" T
  JOIN "INIT$_TB_TARGET_YEAR" Y ON Y.PLAN_YEAR = T.PLAN_YEAR
 WHERE 1=1
   AND Y.MODEL_VERSION < 3
   AND NOT EXISTS (
       SELECT 1 FROM "INIT$_TB_YEAR_TARGET" A
        WHERE A.PLAN_YEAR = T.PLAN_YEAR AND A.SCOPE_CODE = 'STAFF' AND A.TARGET_KEY = TO_CHAR(T.USER_ID)
       )
 GROUP BY T.PLAN_YEAR
     , T.USER_ID
;
-- [ANNUAL_V3_MIGRATE_EXTRAS]
INSERT /*+ DISABLE_PARALLEL_DML NO_PARALLEL */ INTO "INIT$_TB_YEAR_TARGET" (
    PLAN_YEAR
  , SCOPE_CODE
  , TARGET_KEY
  , DEPARTMENT_CODE
  , TARGET_AMOUNT
)
SELECT D.PLAN_YEAR
     , 'DEPARTMENT'
     , D.DEPARTMENT_CODE
     , D.DEPARTMENT_CODE
     , GREATEST(0, SUM(D.TARGET_AMOUNT) - NVL(MAX(P.AMOUNT), 0))
  FROM "INIT$_TB_DEPT_TARGET" D
  JOIN "INIT$_TB_TARGET_YEAR" Y ON Y.PLAN_YEAR = D.PLAN_YEAR
  LEFT JOIN (
       SELECT PLAN_YEAR
            , DEPARTMENT_CODE
            , SUM(TARGET_AMOUNT) AS AMOUNT
         FROM "INIT$_TB_PERSON_TARGET"
        GROUP BY PLAN_YEAR
            , DEPARTMENT_CODE
       ) P ON P.PLAN_YEAR = D.PLAN_YEAR AND P.DEPARTMENT_CODE = D.DEPARTMENT_CODE
 WHERE 1=1
   AND Y.MODEL_VERSION < 3
   AND NOT EXISTS (
       SELECT 1 FROM "INIT$_TB_YEAR_TARGET" A
        WHERE A.PLAN_YEAR = D.PLAN_YEAR AND A.SCOPE_CODE = 'DEPARTMENT' AND A.TARGET_KEY = D.DEPARTMENT_CODE
       )
 GROUP BY D.PLAN_YEAR
     , D.DEPARTMENT_CODE
;
