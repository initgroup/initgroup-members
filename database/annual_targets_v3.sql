-- [ANNUAL_ENTRIES_GET]
SELECT SCOPE_CODE
     , TARGET_KEY
     , USER_ID
     , USER_NAME
     , DEPARTMENT_CODE
     , DEPARTMENT_NAME
     , EMPLOYMENT_TYPE_CODE
     , TARGET_AMOUNT
     , NOTE
  FROM "INIT$_TB_YEAR_TARGET"
 WHERE 1=1
   AND PLAN_YEAR = :year
 ORDER BY SCOPE_CODE
     , DEPARTMENT_CODE
     , USER_NAME
;
-- [ANNUAL_ENTRIES_DELETE]
DELETE /*+ DISABLE_PARALLEL_DML NO_PARALLEL */ FROM "INIT$_TB_YEAR_TARGET"
 WHERE 1=1
   AND PLAN_YEAR = :year
   AND SCOPE_CODE = :scope
;
