-- [PROJECT_REVENUE_GET]
SELECT Y.REVENUE_YEAR
     , Y.REVISION_NO
     , Y.NOTE
     , Y.AMOUNT
  FROM "INIT$_TB_PROJECT_REV_YEAR" Y
 WHERE 1=1
   AND Y.PROJECT_ID = :projectId
 ORDER BY Y.REVENUE_YEAR
;
-- [PROJECT_REVENUE_SCHEMA_STATUS]
SELECT COUNT(*) FROM USER_TABLES WHERE TABLE_NAME = 'INIT$_TB_PROJECT_REV_YEAR'
;
-- [PROJECT_REVENUE_CLOSED_YEARS]
SELECT PLAN_YEAR
  FROM "INIT$_TB_TARGET_YEAR"
 WHERE YEAR_CLOSED_AT IS NOT NULL
;
-- [PROJECT_REVENUE_CLOSED_MONTHS]
SELECT MONTH_KEY
  FROM "INIT$_TB_MONTH_CLOSE"
 WHERE SUBSTR(MONTH_KEY, 1, 4) = TO_CHAR(:year)
;
-- [PROJECT_REVENUE_PROJECT_LOCK]
SELECT PROJECT_ID
  FROM "INIT$_TB_PROJECT"
 WHERE 1=1
   AND PROJECT_ID = :projectId
 FOR UPDATE
;
-- [PROJECT_REVENUE_YEAR_GET]
SELECT REVISION_NO
  FROM "INIT$_TB_PROJECT_REV_YEAR"
 WHERE 1=1
   AND PROJECT_ID = :projectId
   AND REVENUE_YEAR = :year
;
-- [PROJECT_REVENUE_YEAR_SAVE]
MERGE INTO "INIT$_TB_PROJECT_REV_YEAR" Y
USING (SELECT :projectId AS PROJECT_ID, :year AS REVENUE_YEAR FROM DUAL) S
   ON (Y.PROJECT_ID = S.PROJECT_ID AND Y.REVENUE_YEAR = S.REVENUE_YEAR)
WHEN MATCHED THEN UPDATE SET
    Y.REVISION_NO = Y.REVISION_NO + 1
  , Y.AMOUNT = :amount
  , Y.NOTE = :note
  , Y.UPDATED_BY = :actor
  , Y.UPDATED_AT = SYSTIMESTAMP
WHEN NOT MATCHED THEN INSERT (
    PROJECT_ID
  , REVENUE_YEAR
  , REVISION_NO
  , AMOUNT
  , NOTE
  , UPDATED_BY
) VALUES (
    :projectId
  , :year
  , 1
  , :amount
  , :note
  , :actor
)
;
-- [ANNUAL_PROJECT_REVENUE]
SELECT Y.PROJECT_ID
     , Y.REVENUE_YEAR
     , Y.AMOUNT
     , P.PROJECT_NAME
     , P.STATUS_CODE
     , P.DEPARTMENT_CODE
  FROM "INIT$_TB_PROJECT_REV_YEAR" Y
  JOIN "INIT$_TB_PROJECT" P ON P.PROJECT_ID = Y.PROJECT_ID
 WHERE 1=1
   AND Y.REVENUE_YEAR = :year
 ORDER BY Y.PROJECT_ID
;
