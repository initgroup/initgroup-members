-- [AUTH_CORE_TABLE_STATUS]
SELECT TABLE_NAME
  FROM USER_TABLES
 WHERE TABLE_NAME IN (
       'INIT$_TB_USER'
     , 'INIT$_TB_AUTH_SESSION'
     , 'INIT$_TB_NOTICE'
     , 'INIT$_TB_NOTICE_FILE'
 )
;

-- [AUTH_USER_COUNT]
SELECT COUNT(*)
  FROM "INIT$_TB_USER"
;

-- [AUTH_CORE_COLUMN_STATUS]
SELECT TABLE_NAME
     , COLUMN_NAME
  FROM USER_TAB_COLUMNS
 WHERE TABLE_NAME IN (
       'INIT$_TB_USER'
     , 'INIT$_TB_AUTH_SESSION'
     , 'INIT$_TB_NOTICE'
     , 'INIT$_TB_NOTICE_FILE'
 )
;

-- [AUTH_FIRST_ADMIN_LOCK]
LOCK TABLE "INIT$_TB_USER" IN EXCLUSIVE MODE
;

-- [AUTH_SIGNUP_DUPLICATE_COUNT]
SELECT COUNT(*)
  FROM "INIT$_TB_USER"
 WHERE LOGIN_ID = :loginId
    OR LOWER(EMAIL) = LOWER(:email)
;

-- [AUTH_SIGNUP_INSERT_USER]
INSERT INTO "INIT$_TB_USER" (
