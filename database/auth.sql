  , :passwordHash
  , :roleCode
  , :useYn
  , 'Y'
  , SYSTIMESTAMP
)
;

-- [AUTH_LOGIN_USER]
SELECT USER_ID
     , LOGIN_ID
     , USER_NAME
     , EMAIL
     , PASSWORD_HASH
     , USE_YN
     , ROLE_CODE
     , PASSWORD_CHANGE_YN
  FROM "INIT$_TB_USER"
 WHERE LOGIN_ID = :loginId
;

-- [AUTH_SESSION_INSERT]
INSERT INTO "INIT$_TB_AUTH_SESSION" (
    SESSION_TOKEN_HASH
  , USER_ID
  , CREATED_AT
  , LAST_SEEN_AT
  , EXPIRES_AT
) VALUES (
    :sessionTokenHash
  , :userId
  , LOCALTIMESTAMP
  , LOCALTIMESTAMP
  , LOCALTIMESTAMP + NUMTODSINTERVAL(:ttlSeconds, 'SECOND')
)
;

-- [AUTH_SESSION_SELECT]
SELECT U.USER_ID
     , U.LOGIN_ID
     , U.USER_NAME
     , U.EMAIL
     , U.ROLE_CODE
     , U.PASSWORD_CHANGE_YN
  FROM "INIT$_TB_AUTH_SESSION" S
  JOIN "INIT$_TB_USER" U
    ON U.USER_ID = S.USER_ID
 WHERE S.SESSION_TOKEN_HASH = :sessionTokenHash
   AND S.REVOKED_AT IS NULL
   AND S.EXPIRES_AT > LOCALTIMESTAMP
   AND U.USE_YN = 'Y'
;

-- [AUTH_SESSION_TOUCH]
UPDATE "INIT$_TB_AUTH_SESSION"
   SET LAST_SEEN_AT = LOCALTIMESTAMP
     , EXPIRES_AT = LOCALTIMESTAMP + NUMTODSINTERVAL(:ttlSeconds, 'SECOND')
 WHERE SESSION_TOKEN_HASH = :sessionTokenHash
   AND REVOKED_AT IS NULL
;

-- [AUTH_SESSION_REVOKE]
UPDATE "INIT$_TB_AUTH_SESSION"
   SET REVOKED_AT = LOCALTIMESTAMP
 WHERE SESSION_TOKEN_HASH = :sessionTokenHash
   AND REVOKED_AT IS NULL
;

-- [AUTH_SESSION_DELETE_EXPIRED]
DELETE
  FROM "INIT$_TB_AUTH_SESSION"
 WHERE EXPIRES_AT <= LOCALTIMESTAMP
    OR REVOKED_AT IS NOT NULL
;
