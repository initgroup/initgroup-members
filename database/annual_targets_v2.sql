-- [ANNUAL_V2_MIGRATE_TARGETS]
INSERT INTO "INIT$_TB_DEPT_TARGET" (
    PLAN_YEAR
  , MONTH_KEY
  , DEPARTMENT_CODE
  , TARGET_AMOUNT
)
SELECT T.PLAN_YEAR
     , T.MONTH_KEY
     , T.DEPARTMENT_CODE
     , SUM(T.TARGET_AMOUNT)
  FROM "INIT$_TB_PERSON_TARGET" T
 WHERE EXISTS (SELECT 1 FROM "INIT$_TB_TARGET_YEAR" Y WHERE Y.PLAN_YEAR = T.PLAN_YEAR AND Y.MODEL_VERSION < 2)
   AND NOT EXISTS (
       SELECT 1 FROM "INIT$_TB_DEPT_TARGET" D
        WHERE D.PLAN_YEAR = T.PLAN_YEAR AND D.MONTH_KEY = T.MONTH_KEY AND D.DEPARTMENT_CODE = T.DEPARTMENT_CODE
       )
 GROUP BY T.PLAN_YEAR
     , T.MONTH_KEY
     , T.DEPARTMENT_CODE
;
-- [ANNUAL_V2_MIGRATE_EXPENSES]
INSERT /*+ DISABLE_PARALLEL_DML NO_PARALLEL */ INTO "INIT$_TB_COMPANY_EXPENSE" (
    PLAN_YEAR
  , MONTH_KEY
  , AMOUNT
  , NOTE
)
SELECT E.PLAN_YEAR
     , E.MONTH_KEY
     , SUM(E.AMOUNT)
     , 'Migrated from department expenses; original details retained'
  FROM "INIT$_TB_DEPT_EXPENSE" E
 WHERE EXISTS (SELECT 1 FROM "INIT$_TB_TARGET_YEAR" Y WHERE Y.PLAN_YEAR = E.PLAN_YEAR AND Y.MODEL_VERSION < 2)
   AND NOT EXISTS (SELECT 1 FROM "INIT$_TB_COMPANY_EXPENSE" C WHERE C.PLAN_YEAR = E.PLAN_YEAR AND C.MONTH_KEY = E.MONTH_KEY)
 GROUP BY E.PLAN_YEAR
     , E.MONTH_KEY
;
-- [ANNUAL_V2_MIGRATE_PROJECT_DEPT]
UPDATE "INIT$_TB_PROJECT" P
   SET DEPARTMENT_CODE = (
       SELECT MAX(T.CONTRACT_DEPARTMENT) KEEP (DENSE_RANK LAST ORDER BY T.PLAN_YEAR)
         FROM "INIT$_TB_PROJECT_TARGET" T
        WHERE T.PROJECT_ID = P.PROJECT_ID AND T.CONTRACT_DEPARTMENT <> 'UNASSIGNED'
          AND EXISTS (SELECT 1 FROM "INIT$_TB_TARGET_YEAR" Y WHERE Y.PLAN_YEAR = T.PLAN_YEAR AND Y.MODEL_VERSION < 2)
       )
 WHERE P.DEPARTMENT_CODE IS NULL
   AND EXISTS (SELECT 1 FROM "INIT$_TB_PROJECT_TARGET" T JOIN "INIT$_TB_TARGET_YEAR" Y ON Y.PLAN_YEAR = T.PLAN_YEAR WHERE T.PROJECT_ID = P.PROJECT_ID AND T.CONTRACT_DEPARTMENT <> 'UNASSIGNED' AND Y.MODEL_VERSION < 2)
;
